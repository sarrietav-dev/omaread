// node plugin/test.js — checks the pure parts of the widget.
const assert = require('assert')
const M = require('./Model.js')
assert.deepStrictEqual(M.parse('{"reading":[{"title":"A"}]}').reading.length, 1)
assert.ok(M.parse('nope').error)
assert.strictEqual(M.percent(0.374), '37%')
assert.strictEqual(M.timeLeft(65), '1 h 05 min left')
assert.strictEqual(M.timeLeft(12.4), '12 min left')
assert.strictEqual(M.timeLeft(null), '')
assert.strictEqual(M.detail({ fraction: 0.5, chapter: 'Four', minutesLeft: 30 }), '50%  ·  Four  ·  30 min left')
assert.strictEqual(M.tooltip([{ title: 'Outliers', fraction: 0.1 }]), 'Outliers  ·  10%')
assert.strictEqual(M.tooltip([]), 'Omaread')
console.log('plugin model ok')
